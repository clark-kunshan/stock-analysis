// ========== 按需 SWOT 分析 API ==========

/**
 * 提交 SWOT 分析请求（前端 → 服务器队列）
 */
export async function requestSwotAnalysis(stockCode: string, stockName: string): Promise<boolean> {
  try {
    const res = await fetch('/api/swot-request', {
      method: 'POST',
      headers: { 'Content-Type': 'application/json' },
      body: JSON.stringify({ stockCode, stockName }),
    });
    return res.ok;
  } catch {
    return false;
  }
}

/**
 * 查询某只股票的 SWOT 缓存（前端轮询用）
 * 返回 SWOT 数据或 undefined
 */
export async function fetchCachedSwot(stockCode: string): Promise<NonNullable<PEGStock['swot']> | undefined> {
  try {
    const res = await fetch(`/api/swot-cache/${stockCode}`);
    if (!res.ok) return undefined;
    const json = await res.json();
    return json.data;
  } catch {
    return undefined;
  }
}
