/**
 * 根据行业名称查找对应的景气指数
 * @param industry 行业名称（如 "半导体"、"新能源汽车" 等）
 * @returns 景气指数，未匹配时返回 null
 */
export function getProsperityScore(industry: string): number | null {
  if (!industry) return null;
  for (const rule of PROSPERITY_RULES) {
    if (rule.keywords.some(kw => industry.includes(kw))) {
      return rule.score;
    }
  }
  return null;
}
